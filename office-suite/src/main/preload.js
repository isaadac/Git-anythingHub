'use strict';
// Exposes a small, safe API to the renderer. The renderer never gets Node access.
const { contextBridge, ipcRenderer, webFrame } = require('electron');

contextBridge.exposeInMainWorld('atlas', {
  isDesktop: true,
  // How the window is framed (system, mac, overlay or mica): the pages lay out their title bar for it.
  frame: (() => { try { return ipcRenderer.sendSync('app:frame'); } catch { return 'system'; } })(),
  platform: process.platform,
  openDialog: filters => ipcRenderer.invoke('file:open-dialog', filters),
  save: opts => ipcRenderer.invoke('file:save', opts),
  chooseSavePath: opts => ipcRenderer.invoke('file:choose-save-path', opts),
  pendingFile: () => ipcRenderer.invoke('file:pending'),
  exportPdf: opts => ipcRenderer.invoke('file:export-pdf', opts),
  print: () => ipcRenderer.invoke('app:print'),
  recent: () => ipcRenderer.invoke('app:recent'),
  clearRecent: () => ipcRenderer.invoke('app:clear-recent'),
  newWindow: appName => ipcRenderer.invoke('app:new-window', appName),
  openData: (appName, name, data, cloudPath) => ipcRenderer.invoke('app:open-data', { app: appName, name, data, cloudPath }),
  openPath: p => ipcRenderer.invoke('app:open-path', p),
  setTitle: t => ipcRenderer.invoke('app:set-title', t),
  closeNow: () => ipcRenderer.invoke('app:close-now'),
  fullscreen: on => ipcRenderer.invoke('app:fullscreen', on),
  recoverySave: d => ipcRenderer.invoke('recovery:save', d),
  recoveryClear: () => ipcRenderer.invoke('recovery:clear'),
  recoveryList: () => ipcRenderer.invoke('recovery:list'),
  recoveryOpen: id => ipcRenderer.invoke('recovery:open', id),
  recoveryDiscard: id => ipcRenderer.invoke('recovery:discard', id),
  showOpen: () => ipcRenderer.invoke('show:open'),
  showSend: msg => ipcRenderer.invoke('show:send', msg),
  showClose: () => ipcRenderer.invoke('show:close'),
  onShowMessage: cb => ipcRenderer.on('show:message', (_e, msg) => cb(msg)),
  cloudOauthBegin: () => ipcRenderer.invoke('cloud:oauth-begin'),
  cloudOauthWait: req => ipcRenderer.invoke('cloud:oauth-wait', req),
  cloudFetch: req => ipcRenderer.invoke('cloud:fetch', req),
  fetchData: url => ipcRenderer.invoke('net:fetch-data', url),
  cloudBuiltIn: () => ipcRenderer.invoke('cloud:builtin-get'),
  cloudConfigGet: () => ipcRenderer.invoke('cloud:config-get'),
  cloudConfigSet: c => ipcRenderer.invoke('cloud:config-set', c),
  cloudAccountsGet: () => ipcRenderer.invoke('cloud:accounts-get'),
  cloudAccountsSet: t => ipcRenderer.invoke('cloud:accounts-set', t),
  collabHost: () => ipcRenderer.invoke('collab:host'),
  collabJoin: (appName, link) => ipcRenderer.invoke('collab:join', appName, link),
  collabPending: () => ipcRenderer.invoke('collab:pending'),
  aiStatus: () => ipcRenderer.invoke('ai:status'),
  aiSetKey: k => ipcRenderer.invoke('ai:set-key', k),
  aiSetModel: m => ipcRenderer.invoke('ai:set-model', m),
  aiAsk: req => ipcRenderer.invoke('ai:ask', req),
  aiCancel: id => ipcRenderer.invoke('ai:cancel', id),
  onAiDelta: cb => ipcRenderer.on('ai:delta', (_e, d) => cb(d)),
  spellCheck: words => (Array.isArray(words) ? words.slice(0, 50000).map(w => typeof w === 'string' && webFrame.isWordMisspelled(w)) : []),
  spellSuggest: word => (typeof word === 'string' ? webFrame.getWordSuggestions(word).slice(0, 8) : []),
  spellLanguages: () => ipcRenderer.invoke('spell:languages'),
  spellSetLanguages: l => ipcRenderer.invoke('spell:set-languages', l),
  spellAddWord: w => ipcRenderer.invoke('spell:add-word', w),
  setTheme: mode => ipcRenderer.invoke('app:set-theme', mode),
  setLanguage: lang => ipcRenderer.invoke('app:set-language', lang),
  help: section => ipcRenderer.invoke('app:help', section),
  reportError: r => ipcRenderer.invoke('crash:report', r),
  crashStatus: () => ipcRenderer.invoke('crash:status'),
  setCrashReports: on => ipcRenderer.invoke('app:crash-reports', on),
  versionsAdd: (key, name, data, by) => ipcRenderer.invoke('versions:add', key, name, data, by),
  versionsList: key => ipcRenderer.invoke('versions:list', key),
  versionsRead: (key, id) => ipcRenderer.invoke('versions:read', key, id),
  notesList: () => ipcRenderer.invoke('notes:list'),
  notesRead: id => ipcRenderer.invoke('notes:read', id),
  notesWrite: (id, json) => ipcRenderer.invoke('notes:write', id, json),
  notesDelete: id => ipcRenderer.invoke('notes:delete', id),
  onMenu: cb => ipcRenderer.on('menu', (_e, cmd) => cb(cmd))
});
