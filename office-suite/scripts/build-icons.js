'use strict';
// Builds src/renderer/js/icons.js: the Lucide icons (ISC license) the interface uses, and the
// small runtime that draws them. An element asks for an icon with data-icon="name"; JavaScript
// can also use Icons.svg('name') or Icons.set(element, 'name'). Run after using a new icon:
//
//   node scripts/build-icons.js
//
// Names are found in the pages (data-icon="…") and scripts (Icons.svg('…'), Icons.set(x, '…'),
// icon: '…', and "// icons: a b c" comments for names picked at run time); each must exist in lucide-static.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const RENDERER = path.join(ROOT, 'src/renderer');
const LUCIDE = path.join(ROOT, 'node_modules/lucide-static/icons');

function usedNames() {
  const names = new Set();
  for (const f of fs.readdirSync(RENDERER, { recursive: true })) {
    if (!/\.(html|js)$/.test(f) || f.endsWith('icons.js')) continue;
    const text = fs.readFileSync(path.join(RENDERER, f), 'utf8');
    for (const m of text.matchAll(/data-icon="([a-z0-9-]+)"|Icons\.(?:svg|set)\([^'"]*['"]([a-z0-9-]+)['"]|\bicon:\s*['"]([a-z0-9-]+)['"]/g)) names.add(m[1] || m[2] || m[3]);
    // Names chosen at run time are listed in a comment: // icons: bold italic underline
    for (const m of text.matchAll(/\/\/ icons: ([a-z0-9 -]+)/g)) m[1].trim().split(/\s+/).forEach(n => names.add(n));
  }
  return [...names].sort();
}

function body(name) {
  const file = path.join(LUCIDE, name + '.svg');
  if (!fs.existsSync(file)) throw new Error(`No Lucide icon called "${name}"`);
  const svg = fs.readFileSync(file, 'utf8');
  return svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
}

function build() {
  const names = usedNames();
  const map = Object.fromEntries(names.map(n => [n, body(n)]));
  const license = fs.readFileSync(path.join(ROOT, 'node_modules/lucide-static/LICENSE'), 'utf8').trim().split('\n').map(l => ('// ' + l).trimEnd()).join('\n');
  const out = `'use strict';
// Interface icons: Lucide (https://lucide.dev), generated by scripts/build-icons.js — don't edit by hand.
${license}
(function () {
  const ICONS = ${JSON.stringify(map, null, 0).replace(/","/g, '",\n    "').replace(/^\{/, '{\n    ').replace(/\}$/, '\n  }')};
  /** The SVG for an icon (currentColor strokes, 1em square). */
  function svg(name, cls) {
    const b = ICONS[name];
    if (!b) return '';
    return '<svg class="icon' + (cls ? ' ' + cls : '') + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + b + '</svg>';
  }
  /** Draws data-icon elements in a part of the page (all of it by default). */
  function fill(root) {
    const scope = root && root.querySelectorAll ? root : document;
    const els = scope.querySelectorAll('[data-icon]');
    const one = el => { const n = el.getAttribute('data-icon'); if (el.__icon === n) return; el.innerHTML = svg(n); el.__icon = n; };
    if (scope.nodeType === 1 && scope.hasAttribute('data-icon')) one(scope);
    els.forEach(one);
  }
  /** Gives an element an icon (replacing any it had). */
  function set(el, name) { if (!el) return; el.setAttribute('data-icon', name); el.__icon = null; fill(el); }
  window.Icons = { svg, fill, set, has: n => !!ICONS[n], names: () => Object.keys(ICONS) };
  const start = () => {
    fill(document);
    // Icons in content added later (menus, dialogs, panes) and icons that change.
    new MutationObserver(list => {
      for (const m of list) {
        if (m.type === 'attributes') { m.target.__icon = null; fill(m.target); continue; }
        m.addedNodes.forEach(n => { if (n.nodeType === 1) fill(n); });
      }
    }).observe(document.documentElement, { childList: true, subtree: true, attributes: true, attributeFilter: ['data-icon'] });
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
})();
`;
  fs.writeFileSync(path.join(RENDERER, 'js/icons.js'), out);
  return names;
}

module.exports = { build, usedNames };
if (require.main === module) console.log(`icons.js: ${build().length} icons`);
