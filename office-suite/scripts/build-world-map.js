'use strict';
// Builds src/renderer/js/world-map.js: country outlines for map charts in Sheets, from world-atlas
// (countries-110m: Natural Earth data, public domain; world-atlas is ISC licensed). Run after
// updating world-atlas:
//
//   node scripts/build-world-map.js
//
// The TopoJSON is decoded here into plain outlines (longitude/latitude rounded to 0.1°), so the
// app needs no map library and the file stays small.
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const topo = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules/world-atlas/countries-110m.json'), 'utf8'));

const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;
// Arcs are delta-encoded and quantized.
const arcs = topo.arcs.map(arc => { let x = 0, y = 0; return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; }); });
const ring = ids => {
  const out = [];
  for (const id of ids) {
    const pts = id < 0 ? arcs[~id].slice().reverse() : arcs[id];
    pts.forEach((p, i) => { if (i || !out.length) out.push(p); });
  }
  return out;
};
const r1 = v => Math.round(v * 10) / 10;
const countries = topo.objects.countries.geometries.filter(g => g.arcs).map(g => {
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  const rings = polys.flatMap(p => p.map(ring)).map(rg => {
    const flat = [];
    let lx = null, ly = null;
    for (const [x, y] of rg) { const a = r1(x), b = r1(y); if (a !== lx || b !== ly) { flat.push(a, b); lx = a; ly = b; } }
    return flat;
  }).filter(f => f.length >= 6);
  return { name: g.properties.name, rings };
}).filter(c => c.rings.length);

const out = `'use strict';
// Country outlines for map charts, generated by scripts/build-world-map.js — don't edit by hand.
// Natural Earth (public domain), via world-atlas (ISC, Copyright 2013-2019 Michael Bostock).
window.WorldMap = ${JSON.stringify({ countries })};
`;
fs.writeFileSync(path.join(ROOT, 'src/renderer/js/world-map.js'), out);
console.log(`world-map.js: ${countries.length} countries, ${(out.length / 1024).toFixed(0)} KB`);
